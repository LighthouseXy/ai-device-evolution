function officialSpec(value, rawText, sourceUrl, unit) {
  return {
    value,
    ...(unit ? { unit } : {}),
    rawText,
    sourceUrl,
    sourceType: "official",
    confidence: 1,
    verifiedAt: VERIFIED_AT,
  };
}

